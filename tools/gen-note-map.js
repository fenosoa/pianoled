'use strict';
// Generates config/note-map.json: linear interpolation between the LED of the lowest key and the LED of the highest key.
// usage: node tools/gen-note-map.js [--low-note 21] [--high-note 108] [--low-led 2] [--high-led 118] [--out config/note-map.json]
// LED indices are 0-based. Hand-edit the generated table to fix individual notes.
const fs = require('node:fs');
const path = require('node:path');
const { LED_COUNT } = require('../src/constants');

const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : def;
};

const lowNote = Number(opt('low-note', 21));
const highNote = Number(opt('high-note', 108));
const lowLed = Number(opt('low-led', 2));
const highLed = Number(opt('high-led', 118));
const out = path.resolve(process.cwd(), opt('out', 'config/note-map.json'));

for (const [n, v] of Object.entries({ lowNote, highNote, lowLed, highLed })) {
  if (!Number.isInteger(v)) throw new Error(`${n} must be an integer`);
}
if (highNote <= lowNote) throw new Error('high-note must be > low-note');
for (const l of [lowLed, highLed]) if (l < 0 || l >= LED_COUNT) throw new Error(`LED ${l} outside [0,${LED_COUNT - 1}]`);

const step = (highLed - lowLed) / (highNote - lowNote);
const map = {};
for (let n = lowNote; n <= highNote; n++) map[n] = Math.round(lowLed + (n - lowNote) * step);

const json = {
  _comment: `Generated by tools/gen-note-map.js: notes ${lowNote}..${highNote} -> LEDs ${lowLed}..${highLed} (${step.toFixed(4)} LED/key). Edit individual entries to correct offsets.`,
  map,
};
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(json, null, 2) + '\n');
console.log(`wrote ${out} (${Object.keys(map).length} notes, ${step.toFixed(4)} LED/key)`);
