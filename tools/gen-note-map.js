'use strict';
// Generates config/note-map.json (LED indices are 0-based).
//
// Two modes:
//   ends    : linear interpolation between the LED of the lowest key and the LED of the highest key.
//             node tools/gen-note-map.js [--low-note 36] [--high-note 96] [--low-led 118] [--high-led 2]
//   anchors : keeps the listed notes of the existing table as calibrated values and recomputes every
//             other note by linear interpolation between its two nearest anchors.
//             node tools/gen-note-map.js --anchors 36-40,60-63,93-96
// Common: [--out config/note-map.json]. Hand-edit the generated table to fix individual notes.
const fs = require('node:fs');
const path = require('node:path');
const { LED_COUNT } = require('../src/constants');

const args = process.argv.slice(2);
const opt = (name, def) => {
  const i = args.indexOf(`--${name}`);
  return i >= 0 ? args[i + 1] : def;
};
const out = path.resolve(process.cwd(), opt('out', 'config/note-map.json'));

function checkLed(led, note) {
  if (!Number.isInteger(led) || led < 0 || led >= LED_COUNT) {
    throw new Error(`LED ${led}${note !== undefined ? ` (note ${note})` : ''} outside [0,${LED_COUNT - 1}]`);
  }
}

// "36-40,60,93-96" -> [36,37,38,39,40,60,93,94,95,96]
function parseNoteList(spec) {
  const notes = new Set();
  for (const part of spec.split(',')) {
    const [a, b = a] = part.split('-').map(Number);
    if (!Number.isInteger(a) || !Number.isInteger(b) || b < a) throw new Error(`invalid note range "${part}"`);
    for (let n = a; n <= b; n++) notes.add(n);
  }
  return [...notes].sort((x, y) => x - y);
}

function fromEnds() {
  const lowNote = Number(opt('low-note', 36));
  const highNote = Number(opt('high-note', 96));
  const lowLed = Number(opt('low-led', 118));
  const highLed = Number(opt('high-led', 2));
  for (const [n, v] of Object.entries({ lowNote, highNote })) if (!Number.isInteger(v)) throw new Error(`${n} must be an integer`);
  if (highNote <= lowNote) throw new Error('high-note must be > low-note');
  checkLed(lowLed);
  checkLed(highLed);
  const step = (highLed - lowLed) / (highNote - lowNote);
  const map = {};
  for (let n = lowNote; n <= highNote; n++) map[n] = Math.round(lowLed + (n - lowNote) * step);
  return { map, comment: `notes ${lowNote}..${highNote} -> LEDs ${lowLed}..${highLed} (${step.toFixed(4)} LED/key)` };
}

function fromAnchors(spec) {
  const current = JSON.parse(fs.readFileSync(out, 'utf8'));
  const table = current.map || current;
  const anchors = parseNoteList(spec).map((note) => {
    if (!(note in table)) throw new Error(`anchor note ${note} missing from ${out}`);
    const led = table[note];
    checkLed(led, note);
    return { note, led };
  });
  if (anchors.length < 2) throw new Error('need at least 2 anchor notes');

  const map = {};
  for (let i = 0; i < anchors.length - 1; i++) {
    const a = anchors[i];
    const b = anchors[i + 1];
    const step = (b.led - a.led) / (b.note - a.note);
    // Integer arithmetic before rounding avoids 56.4999… style float artifacts.
    for (let n = a.note; n < b.note; n++) map[n] = Math.round(a.led + ((n - a.note) * (b.led - a.led)) / (b.note - a.note));
    if (b.note - a.note > 1) console.log(`  ${a.note}..${b.note}: ${step.toFixed(4)} LED/key`);
  }
  const last = anchors[anchors.length - 1];
  map[last.note] = last.led;
  return { map, comment: `anchors ${spec} kept, other notes interpolated between neighbouring anchors` };
}

const anchorSpec = opt('anchors', null);
const { map, comment } = anchorSpec ? fromAnchors(anchorSpec) : fromEnds();

const json = {
  _comment: `Generated by tools/gen-note-map.js: ${comment}. Edit individual entries to correct offsets.`,
  map,
};
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, JSON.stringify(json, null, 2) + '\n');
console.log(`wrote ${out} (${Object.keys(map).length} notes)`);
